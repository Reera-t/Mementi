import AppKit
import Foundation

public final class ClipboardObserver: ObservableObject {
    public static let shared = ClipboardObserver()

    private let pasteboard = NSPasteboard.general
    private var lastChangeCount: Int
    private var timer: Timer?
    private var suppressNextChange = false

    private init() {
        self.lastChangeCount = pasteboard.changeCount
    }

    public func start() {
        stop()
        lastChangeCount = pasteboard.changeCount
        timer = Timer.scheduledTimer(withTimeInterval: 0.5, repeats: true) { [weak self] _ in
            self?.checkForChanges()
        }
    }

    public func stop() {
        timer?.invalidate()
        timer = nil
    }

    private func checkForChanges() {
        guard pasteboard.changeCount != lastChangeCount else { return }
        lastChangeCount = pasteboard.changeCount

        if suppressNextChange {
            suppressNextChange = false
            return
        }

        // Avoid capturing transient/sensitive clips (Apple Keychain, 1Password, KeePassXC, Bitwarden, etc.)
        if let types = pasteboard.types {
            let sensitiveTypes = [
                "org.nspasteboard.ConcealedType",
                "org.nspasteboard.TransientType",
                "org.nspasteboard.AutoGeneratedType",
                "com.agilebits.onepassword",
                "de.vitalif.keepassxc.ConcealedType",
                "net.8bit.bitwarden"
            ]
            let isSensitive = types.contains { t in
                let lower = t.rawValue.lowercased()
                return lower.contains("concealed") ||
                       lower.contains("transient") ||
                       lower.contains("password") ||
                       sensitiveTypes.contains(t.rawValue)
            }
            if isSensitive {
                return
            }
        }

        guard let text = pasteboard.string(forType: .string) else { return }
        let trimmed = text.trimmingCharacters(in: .whitespacesAndNewlines)
        // Guard against massive payloads (> 1MB / 1,000,000 chars) to prevent memory spikes
        guard !trimmed.isEmpty && trimmed.count <= 1_000_000 else { return }

        DispatchQueue.main.async {
            StorageManager.shared.addClip(content: text)
        }
    }

    /// Copy item back into system pasteboard without triggering duplicate observer cycle
    public func copyToPasteboard(text: String) {
        suppressNextChange = true
        pasteboard.clearContents()
        pasteboard.setString(text, forType: .string)
        lastChangeCount = pasteboard.changeCount
    }
}
